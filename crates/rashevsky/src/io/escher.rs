//! Escher (King et al. 2015) flux data and map files, schema 1-0-0.

use super::layout::Layout;
use crate::model::Model;
use serde_json::{Map, Value, json};
use std::collections::BTreeMap;

/// Flux data in the form Escher reads as `reaction_data`.
pub fn reaction_data(model: &Model, fluxes: &[f64]) -> BTreeMap<String, f64> {
    model.reactions.iter().zip(fluxes).map(|(r, v)| (r.id.clone(), *v)).collect()
}

/// Writes an Escher map for a layout. Each reaction is a midmarker with one segment to each of its
/// primary metabolites, and currency metabolites stay in the reaction's list but get no node.
pub fn map_json(model: &Model, layout: &Layout, name: &str) -> Value {
    let mut nodes = Map::new();
    let mut reactions = Map::new();
    let mut next_id = 1usize;
    let mut fresh = || {
        let id = next_id.to_string();
        next_id += 1;
        id
    };
    let mut node_of_met: BTreeMap<usize, String> = BTreeMap::new();
    for p in &layout.metabolites {
        let met = &model.metabolites[p.index];
        let id = fresh();
        nodes.insert(id.clone(), json!({
            "node_type": "metabolite",
            "x": p.x,
            "y": p.y,
            "label_x": p.x + 12.0,
            "label_y": p.y - 12.0,
            "bigg_id": met.id,
            "name": met.name,
            "node_is_primary": true,
        }));
        node_of_met.insert(p.index, id);
    }
    for p in &layout.reactions {
        let r = &model.reactions[p.index];
        let mid = fresh();
        nodes.insert(mid.clone(), json!({"node_type": "midmarker", "x": p.x, "y": p.y}));
        let mut segments = Map::new();
        for &(i, _) in &r.stoichiometry {
            if let Some(met_node) = node_of_met.get(&i) {
                let sid = fresh();
                segments.insert(sid, json!({"from_node_id": mid, "to_node_id": met_node, "b1": null, "b2": null}));
            }
        }
        let gene_ids = {
            let mut out = Vec::new();
            r.gpr.genes(&mut out);
            out.sort_unstable();
            out.dedup();
            out
        };
        let rid = fresh();
        reactions.insert(rid, json!({
            "name": r.name,
            "bigg_id": r.id,
            "reversibility": r.lb < 0.0 && r.ub > 0.0,
            "label_x": p.x + 10.0,
            "label_y": p.y + 16.0,
            "gene_reaction_rule": r.gpr.to_rule(&|g| model.genes[g].id.clone()),
            "genes": gene_ids.iter().map(|&g| json!({"bigg_id": model.genes[g].id, "name": model.genes[g].name})).collect::<Vec<_>>(),
            "metabolites": r.stoichiometry.iter().map(|&(i, c)| json!({"coefficient": c, "bigg_id": model.metabolites[i].id})).collect::<Vec<_>>(),
            "segments": segments,
        }));
    }
    json!([
        {
            "map_name": name,
            "map_id": format!("rashevsky-{name}"),
            "map_description": "Generated by Rashevsky with a force-directed layout",
            "homepage": "https://escher.github.io",
            "schema": "https://escher.github.io/escher/jsonschema/1-0-0#",
        },
        {
            "reactions": reactions,
            "nodes": nodes,
            "text_labels": {},
            "canvas": {"x": 0.0, "y": 0.0, "width": layout.width, "height": layout.height},
        },
    ])
}
